#!/usr/bin/env python3
"""
OpenShift AI Pipeline Teardown Script
Cleans up all cluster resources, PVCs, secrets, DSPA instances, KServe
deployments, and local configuration generated by setup.py and pipeline runs.
"""

import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

def print_header(title: str):
    print("\n" + "=" * 65)
    print(f"  {title}")
    print("=" * 65)

def run_cmd(cmd: list, check: bool = False, capture: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(
        cmd,
        check=check,
        text=True,
        capture_output=capture
    )

def get_target_namespace() -> str:
    # Try reading from .env first
    if Path(".env").exists():
        with open(".env") as f:
            for line in f:
                if line.startswith("NAMESPACE="):
                    ns = line.split("=", 1)[1].strip()
                    if ns:
                        return ns
    # Fallback to active oc project
    try:
        res = run_cmd(["oc", "project", "-q"], check=True)
        return res.stdout.strip()
    except Exception:
        return ""

def main():
    print("=" * 65)
    print("  OpenShift AI Pipeline Teardown (destroy.py)")
    print("=" * 65)
    print("This script will delete all cluster resources and local files")
    print("created during setup, returning the project to a fresh state.\n")

    # 1. Verify oc CLI
    try:
        run_cmd(["which", "oc"], check=True)
    except Exception:
        print("[ERROR] 'oc' CLI not found in PATH.")
        sys.exit(1)

    namespace = get_target_namespace()
    if not namespace:
        namespace = input("Enter target OpenShift namespace: ").strip()
    else:
        confirm_ns = input(f"Target namespace is '{namespace}'. Proceed? [Y/n]: ").strip().lower()
        if confirm_ns not in ("", "y", "yes"):
            namespace = input("Enter target namespace: ").strip()

    if not namespace:
        print("[ERROR] No namespace specified. Aborting.")
        sys.exit(1)

    confirm_all = input(f"\n⚠️  Are you sure you want to DESTROY all pipeline & serving resources in '{namespace}'? [y/N]: ").strip().lower()
    if confirm_all not in ("y", "yes"):
        print("Teardown cancelled.")
        sys.exit(0)

    # 2. Delete KServe and Serving Resources FIRST
    print_header("1. Deleting KServe Model Serving Resources")
    print(f"Cleaning up InferenceServices and ServingRuntimes in '{namespace}'...")
    run_cmd(["oc", "delete", "inferenceservice", "char-completion", "-n", namespace, "--timeout=30s", "--ignore-not-found"])
    run_cmd(["oc", "delete", "servingruntime", "char-completion-runtime", "-n", namespace, "--ignore-not-found"])
    run_cmd(["oc", "delete", "secret", "kserve-s3-secret", "-n", namespace, "--ignore-not-found"])
    run_cmd(["oc", "delete", "sa", "kserve-sa", "-n", namespace, "--ignore-not-found"])
    run_cmd(["oc", "delete", "bc", "char-completion-serving", "-n", namespace, "--ignore-not-found"])
    run_cmd(["oc", "delete", "is", "char-completion-serving", "-n", namespace, "--ignore-not-found"])
    run_cmd(["oc", "delete", "deployment", "char-completion", "-n", namespace, "--ignore-not-found"])
    run_cmd(["oc", "delete", "svc", "char-completion", "-n", namespace, "--ignore-not-found"])
    run_cmd(["oc", "delete", "route", "char-completion", "-n", namespace, "--ignore-not-found"])
    print("  [OK] Model serving resources removed.")

    # 3. Delete DSPA
    print_header("2. Deleting DataSciencePipelinesApplication (DSPA)")
    print(f"Deleting DSPA 'dspa' in namespace '{namespace}'...")
    res = run_cmd(["oc", "delete", "dspa", "dspa", "-n", namespace, "--timeout=60s", "--ignore-not-found"])
    if res.returncode == 0:
        print("  [OK] DSPA deletion initiated. Waiting for operator cleanup...")
        time.sleep(5)
    else:
        print(f"  [INFO] {res.stderr.strip() if res.stderr else 'DSPA not found.'}")

    # 4. Delete Tekton CI/CD resources if present
    print_header("3. Deleting Tekton CI/CD Resources")
    for tekton_file in ["tekton/pipelinerun.yaml", "tekton/pipeline.yaml", "tekton/task-compile-submit.yaml", "tekton/rbac.yaml"]:
        if Path(tekton_file).exists():
            run_cmd(["oc", "delete", "-f", tekton_file, "-n", namespace, "--ignore-not-found"])
    run_cmd(["oc", "delete", "pipelineruns", "--all", "-n", namespace, "--ignore-not-found"])
    print("  [OK] Tekton resources removed.")

    # 5. Delete Deployments, Services, Secrets & NetworkPolicies FIRST (before PVCs)
    print_header("4. Deleting Deployments, Services & Secrets")
    run_cmd(["oc", "delete", "deployment", "minio", "-n", namespace, "--now", "--ignore-not-found"])
    run_cmd(["oc", "delete", "svc", "minio", "-n", namespace, "--ignore-not-found"])
    run_cmd(["oc", "delete", "secret", "pipeline-s3-secret", "-n", namespace, "--ignore-not-found"])
    run_cmd(["oc", "delete", "networkpolicy", "allow-from-redhat-ods-app-to-minio", "-n", namespace, "--ignore-not-found"])
    print("  [OK] Deployments, services, and secrets removed.")

    # 6. Delete Workload & Lingering Pods
    print_header("5. Cleaning Up Workload Pods")
    run_cmd(["oc", "delete", "pods", "-l", "pipelines.kubeflow.org/v2_component=true", "-n", namespace, "--now", "--ignore-not-found"])
    run_cmd(["oc", "delete", "pods", "-l", "app=minio", "-n", namespace, "--now", "--ignore-not-found"])
    
    # Also delete any leftover ocp pods
    try:
        pods_res = run_cmd(["oc", "get", "pods", "-n", namespace, "-o", "jsonpath={.items[*].metadata.name}"])
        pod_names = pods_res.stdout.split()
        for p in pod_names:
            if p.startswith("ocp-") or p.startswith("minio-") or p.startswith("char-completion"):
                print(f"  Deleting pod: {p}")
                run_cmd(["oc", "delete", "pod", p, "-n", namespace, "--now", "--ignore-not-found"])
    except Exception:
        pass
    print("  [OK] Pods cleaned up.")

    # 7. Delete PersistentVolumeClaims (PVCs) AFTER pods are gone
    print_header("6. Deleting Storage Claims (PVCs)")
    pvcs_to_delete = ["mariadb-dspa", "minio-dspa", "minio-pvc"]
    for pvc in pvcs_to_delete:
        print(f"Deleting PVC '{pvc}'...")
        run_cmd(["oc", "delete", "pvc", pvc, "-n", namespace, "--timeout=15s", "--ignore-not-found"])
    print("  [OK] PVCs deleted.")

    # 8. Local File Cleanup
    print_header("7. Cleaning Up Local Files")
    if Path(".env").exists():
        os.remove(".env")
        print("  [OK] Removed local .env")
        
    if Path("pipeline.yaml").exists():
        os.remove("pipeline.yaml")
        print("  [OK] Removed compiled pipeline.yaml")

    if Path("artifacts").exists():
        shutil.rmtree("artifacts")
        print("  [OK] Removed local artifacts directory.")

    clean_venv = input("\nAlso delete Python virtual environment (.venv)? [y/N]: ").strip().lower()
    in_active_venv = bool(os.environ.get("VIRTUAL_ENV"))
    if clean_venv in ("y", "yes") and Path(".venv").exists():
        shutil.rmtree(".venv")
        print("  [OK] Removed .venv directory.")

    print_header("Teardown Complete!")
    print("All cluster resources and local files have been deleted.")
    print("You can now run 'python3 setup.py' fresh without conflicts.")

    if in_active_venv:
        print("\n" + "-" * 65)
        print("👉 You are currently inside the Python virtual environment.")
        print("   To exit it, type in your terminal:")
        print("       deactivate")
        print("-" * 65)

    print("=" * 65 + "\n")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\n\nTeardown aborted by user.")
        sys.exit(1)
